"""exports.txt (dumpbin で取った system opengl32.dll の「序数 名前」一覧) から
転送用の stubs.c と opengl32.def を作る。HOOKED の関数だけは hook.c 側の実装へ向ける。"""

import os
import sys

HOOKED = {"glTexImage2D", "glGetIntegerv"}

here = os.path.dirname(os.path.abspath(__file__))
rows = []
with open(os.path.join(here, "exports.txt"), encoding="ascii") as f:
    for line in f:
        line = line.strip()
        if line:
            ordinal, name = line.split()
            rows.append((int(ordinal), name))

with open(os.path.join(here, "stubs.c"), "w", encoding="ascii", newline="\r\n") as f:
    f.write("/* generated by gen.py - do not edit */\n")
    f.write("#include <windows.h>\n\n")
    f.write(f"#define REAL_COUNT {len(rows)}\n")
    f.write("FARPROC g_real[REAL_COUNT];\n")
    f.write("const char *g_real_names[REAL_COUNT] = {\n")
    for _, name in rows:
        f.write(f'    "{name}",\n')
    f.write("};\n\n")
    for i, (_, name) in enumerate(rows):
        if name in HOOKED:
            continue
        f.write(f"__declspec(naked) void stub_{i}(void) {{ __asm jmp dword ptr [g_real + {i * 4}] }}\n")

with open(os.path.join(here, "opengl32.def"), "w", encoding="ascii", newline="\r\n") as f:
    f.write("LIBRARY opengl32\nEXPORTS\n")
    for i, (ordinal, name) in enumerate(rows):
        target = f"hook_{name}" if name in HOOKED else f"stub_{i}"
        f.write(f"    {name}={target} @{ordinal}\n")

print(f"{len(rows)} exports, hooked: {sorted(HOOKED)}")
